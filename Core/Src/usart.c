UART_HandleTypeDef huart6;

/* USART6 init function */

void MX_USART6_UART_Init(void)
{

  huart6.Instance = USART6;
  huart6.Init.BaudRate = 115200;
  huart6.Init.WordLength = UART_WORDLENGTH_8B;
  huart6.Init.StopBits = UART_STOPBITS_1;
  huart6.Init.Parity = UART_PARITY_NONE;
  huart6.Init.Mode = UART_MODE_TX_RX;
  huart6.Init.HwFlowCtl = UART_HWCONTROL_NONE;
  huart6.Init.OverSampling = UART_OVERSAMPLING_16;
  if (HAL_UART_Init(&huart6) != HAL_OK)
  {
    Error_Handler();
  }

}

void HAL_UART_MspInit(UART_HandleTypeDef* uartHandle)
{

  if(uartHandle->Instance==USART6)
  {
  /* USER CODE BEGIN USART6_MspInit 0 */

  /* USER CODE END USART6_MspInit 0 */
    /* USART6 clock enable */
    __HAL_RCC_USART6_CLK_ENABLE();
  
    /**USART6 GPIO Configuration (собственный драйвер, тактирование порта включается в gpio_init)
    PC6     ------> USART6_TX
    PC7     ------> USART6_RX
    */
    const gpio_config_t uart_pins = {
      .mode  = PIN_MODE_AF,
      .otype = PIN_OTYPE_PUSHPULL,
      .speed = PIN_SPEED_VERY_HIGH,
      .pull  = PIN_PULL_NONE,
      .af    = 8,                /* AF8 = USART6 */
    };
    if (gpio_init(GPIOC, GPIO_PIN(6) | GPIO_PIN(7), &uart_pins) != GPIO_OK)
    {
      Error_Handler();
    }

  /* USER CODE BEGIN USART6_MspInit 1 */

  /* USER CODE END USART6_MspInit 1 */
  }
}

